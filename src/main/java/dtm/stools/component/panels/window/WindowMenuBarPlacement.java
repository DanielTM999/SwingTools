package dtm.stools.component.panels.window;

/** Determines where a window menu bar is rendered. */
public enum WindowMenuBarPlacement {
    /** Renders the menu in its own row, between the title bar and the content. */
    BELOW_TITLE_BAR,
    /** Renders the menu inside the title bar, on the same row as the window controls. */
    TITLE_BAR
}
