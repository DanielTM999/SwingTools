package dtm.stools.component.panels.window;

/**
 * Initial position of a {@link WindowPanel} inside its desktop.
 * {@link #CASCADE} preserves the default automatic placement behavior.
 */
public enum WindowPosition {
    CASCADE,
    CENTER,
    LEFT,
    RIGHT,
    TOP,
    BOTTOM,
    TOP_LEFT,
    TOP_RIGHT,
    BOTTOM_LEFT,
    BOTTOM_RIGHT
}
